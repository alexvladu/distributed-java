BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE trades (
        trade_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        portfolio_id NUMBER NOT NULL,
        symbol VARCHAR2(12) NOT NULL,
        side VARCHAR2(4) NOT NULL,
        quantity NUMBER(18,6) NOT NULL,
        executed_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT trades_side_ck CHECK (side IN (''BUY'', ''SELL'')),
        CONSTRAINT trades_quantity_ck CHECK (quantity > 0)
    )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

INSERT INTO trades (portfolio_id, symbol, side, quantity)
SELECT 1, 'AAPL', 'BUY', 1 FROM dual
WHERE NOT EXISTS (SELECT 1 FROM trades WHERE portfolio_id = 1 AND symbol = 'AAPL');
COMMIT;
